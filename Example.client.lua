-- Example LocalScript. Place in StarterPlayerScripts.
-- Expected layout: ReplicatedStorage.Glassline.{Library,Controls,ThemeManager,SaveManager}
local ReplicatedStorage=game:GetService("ReplicatedStorage")
local folder=ReplicatedStorage:WaitForChild("Glassline")
local Library=require(folder:WaitForChild("Library"))
local Controls=require(folder:WaitForChild("Controls"))
local ThemeManager=require(folder:WaitForChild("ThemeManager"))
local SaveManager=require(folder:WaitForChild("SaveManager"))
local Window=Library:CreateWindow({Title="GLASSLINE",Footer="LIQUID GLASS UI  •  v1.0",ToggleKeybind=Enum.KeyCode.RightControl})
ThemeManager:SetLibrary(Library); SaveManager:SetLibrary(Library)
local Main=Library:AddTab("Main","home")
local Player=Library:AddTab("Player","user")
local Settings=Library:AddTab("Settings","settings")
local intro=Main:AddGroupbox({Name="Welcome",Side="Left",Description="A compact glass-style UI framework."})
intro:AddLabel("Build a clean interface with tabs, groupboxes, toggles, sliders, inputs, dropdowns and notifications.",true)
intro:AddDivider()
intro:AddButton({Text="Test notification",Func=function() Library:Notify({Title="Glassline",Description="Your UI is running.",Time=3}) end})
intro:AddToggle("DemoToggle",{Text="Demo toggle",Default=false,Callback=function(v) print("Demo toggle:",v) end})
local playerBox=Player:AddGroupbox({Name="Demo controls",Side="Left",Description="These controls are examples for your own experience."})
playerBox:AddSlider("DemoSlider",{Text="Demo value",Default=16,Min=0,Max=100,Rounding=0,Callback=function(v) print("Slider:",v) end})
playerBox:AddInput("DemoInput",{Text="Text input",Default="",Placeholder="Type something...",Callback=function(v) print("Input:",v) end})
playerBox:AddDropdown("Theme",{Text="Theme preset",Values={"Glass","Mono","Slate"},Default="Glass",Callback=function(v) ThemeManager:Apply(v); print("Theme palette set to",v,"(existing controls recolor after rebuilding the window)") end})
local settings=Settings:AddGroupbox({Name="Configuration",Side="Left",Description="Snapshots print as JSON in the Output window."})
settings:AddButton({Text="Print config JSON",Func=function() print(SaveManager:Encode()); Library:Notify({Title="Configuration",Description="Snapshot printed to Output.",Time=3}) end})
settings:AddButton({Text="Unload UI",Func=function() Library:Unload() end})
Library:Notify({Title="Glassline loaded",Description="Press Right Ctrl to hide/show the window.",Time=4})
